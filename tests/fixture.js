(async () => {
  const results = [];
  const pause = () => new Promise(resolve => setTimeout(resolve, 250));
  const visible = selector => {
    const el = document.querySelector(selector);
    return el && el.getBoundingClientRect().width > 0 && el.getBoundingClientRect().height > 0;
  };
  const check = (condition, name) => {
    results.push(`${condition ? "PASS" : "FAIL"} ${name}`);
    if (!condition) throw new Error(name);
  };
  const shared = window.CleanZhihuSettings;
  const set = settings => chrome.storage.local.set({ [shared.key]: { ...shared.defaults, ...settings } });
  try {
    await pause();
    if (new URLSearchParams(location.search).has("stored-image-less")) {
      check(!visible("#feed-image") && document.querySelector("[data-cz-fish-toggle]").getAttribute("aria-pressed") === "true", "stored no-image mode restored on page initialization");
      check(document.documentElement.style.getPropertyValue("--cz-content-width") === "1120px", "other stored preferences preserved");
      await set({});
    }
    check(!visible("#mascot") && visible("#back-to-top"), "Hi mascot hidden while back-to-top retained");
    check(visible("[data-cz-fish-toggle]") && document.querySelector("[data-cz-fish-toggle]").nextElementSibling.matches(".SearchBar"), "fish button placed before search");
    check(visible("#feed-image") && visible("#feed-video"), "media visible by default");
    document.querySelector("[data-cz-fish-toggle] svg path").dispatchEvent(new MouseEvent("click", { bubbles: true }));
    await pause();
    check(!visible("#feed-image") && !visible("#feed-cover") && !visible("#feed-video"), "fish click hides cover, image and video");
    check(visible("#header-avatar") && visible("#author-avatar") && visible("#author-avatar-picture"), "header and author avatars retained in no-image mode");
    check(getComputedStyle(document.querySelector("#comment-avatar")).backgroundImage !== "none", "background-based comment avatar retained");
    check(getComputedStyle(document.querySelector("#feed-background")).backgroundImage === "none", "background images hidden");
    check(visible("#answer-text") && visible("[data-cz-fish-toggle] svg") && visible(".SearchBar"), "text, search and fish icon remain usable");
    check((await chrome.storage.local.get(shared.key))[shared.key].imageLess, "fish preference persisted");
    const lazyImage = document.querySelector("#feed-image").cloneNode();
    lazyImage.id = "lazy-image";
    document.querySelector("#media-fixture").append(lazyImage);
    check(!visible("#lazy-image"), "late-loaded images hidden immediately");
    const lazyAvatar = document.querySelector("#header-avatar").cloneNode();
    lazyAvatar.id = "lazy-avatar";
    document.querySelector("#media-fixture").append(lazyAvatar);
    check(visible("#lazy-avatar"), "late-loaded avatar retained immediately");
    document.querySelector("[data-cz-fish-toggle]").click();
    await pause();
    check(visible("#feed-image") && visible("#feed-video") && visible("#lazy-image"), "second fish click restores media");
    await set({ hideMascot: false });
    check(visible("#mascot"), "mascot preference can restore entry");
    await set({});
    check(!visible(".Topstory-sideBar"), "P2 sidebar hidden");
    let sidebar = document.querySelector("#sidebar");
    sidebar.className = "GlobalSideBar";
    sidebar.removeAttribute("data-cz-sidebar");
    check(!visible("#sidebar"), "GlobalSideBar variant hidden immediately");
    // Reproduce a separately named wrapper with a positioned sticky sidebar.
    const replacement = document.createElement("div");
    replacement.id = "sidebar";
    replacement.className = "new-layout-wrapper";
    replacement.innerHTML = '<div class="Sticky" style="position:absolute;right:0;top:80px;width:294px;background:white">创作中心<div>大家都在搜</div><div>盐言作者平台</div></div>';
    sidebar.replaceWith(replacement);
    await pause();
    check(!visible("#sidebar .Sticky"), "late unknown wrapper and positioned sidebar hidden");
    await set({ hideSidebar: false });
    check(visible("#sidebar .Sticky"), "sidebar setting restores wrapper and sticky child");
    await set({});
    check(!visible("#sidebar .Sticky"), "sidebar setting hides positioned child again");
    replacement.querySelector(".Sticky").textContent = "普通内容";
    await pause();
    check(visible("#sidebar .Sticky"), "reused non-sidebar branch is restored");
    sidebar.className = "Topstory-sideBar";
    replacement.replaceWith(sidebar);
    await pause();
    check(!visible("#ai-nav") && !visible("#story-nav"), "P3 AI Works / story hidden");
    check(!visible("#ai-answer") && !visible("#plus"), "P4 direct answer / plus hidden");
    check(visible("#messages") && visible("#answer-text") && visible(".composer"), "messages, composer and answer preserved");
    const width = document.querySelector(".Topstory-mainColumn").getBoundingClientRect().width;
    const viewportWidth = document.documentElement.clientWidth;
    check(Math.abs(width - Math.min(1440, viewportWidth - (innerWidth <= 700 ? 16 : 32))) < 2, "feed fills centered wide container");
    check(document.documentElement.scrollWidth <= viewportWidth, "no horizontal overflow at current viewport");
    await set({ enabled: false });
    check(visible("#mascot") && !visible("[data-cz-fish-toggle]"), "master switch restores mascot and hides injected button");
    check(visible(".Topstory-sideBar") && visible("#ai-nav") && visible("#plus"), "master switch restores original elements");
    check(document.querySelector(".Topstory-mainColumn").getBoundingClientRect().width === 694, "master switch restores original width");
    await set({ hideAiNav: false, hideHeaderActions: false, hideSidebar: false });
    check(visible("#ai-nav") && visible("#ai-answer") && visible(".Topstory-sideBar"), "individual visibility controls work");
    await set({ width: 1120 });
    check(document.documentElement.style.getPropertyValue("--cz-content-width") === "1120px", "custom width applied");
    await set({ width: 0 });
    check(document.documentElement.style.getPropertyValue("--cz-content-width").includes("100vw"), "window-fill mode applied");
    const dynamic = document.createElement("li");
    dynamic.innerHTML = '<a id="dynamic-story" href="/new-story">故事</a>';
    document.querySelector(".AppHeader ul").append(dynamic);
    await pause();
    check(!visible("#dynamic-story"), "late-mounted navigation hidden");
    dynamic.querySelector("a").textContent = "发现";
    await pause();
    check(visible("#dynamic-story"), "reused React element is reclassified");
    dynamic.remove();
    const original = document.querySelector(".AppHeader");
    original.replaceWith(original.cloneNode(true));
    await pause();
    check(!visible("#plus") && visible("#messages"), "header replacement handled");
    check(document.querySelectorAll("[data-cz-fish-toggle]").length === 1, "header replacement keeps exactly one fish");
    document.querySelector("[data-cz-fish-toggle]").click();
    await pause();
    check(!visible("#feed-image"), "fish click still works after header cloning");
    await set({ imageLess: true, enabled: false });
    check(visible("#feed-image"), "master switch restores media even with no-image preference saved");
    await set({});
    document.body.dataset.testStatus = "passed";
  } catch (error) {
    document.body.dataset.testStatus = "failed";
    results.push(error.message);
  }
  document.getElementById("results").textContent = results.join("\n");
})();
